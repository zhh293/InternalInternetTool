package dev.tunnel;

import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.security.SecureRandom;
import java.util.HashMap;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.TimeUnit;

/** Downloadable distribution entry point; legacy Server/Client mains remain available. */
public final class Main {
  private Main() {}

  public static void main(String[] args) throws Exception {
    if (args.length == 0 || isHelp(args[0])) {
      if (args.length > 2) throw new IllegalArgumentException("Usage: tunnel help [command]");
      if (args.length == 2) commandHelp(args[1]);
      else help();
      return;
    }
    if ("--version".equals(args[0]) || "version".equals(args[0])) {
      Properties version = new Properties();
      try (java.io.InputStream in = Main.class.getResourceAsStream("/tunnel-version.properties")) {
        if (in != null) version.load(in);
      }
      System.out.println("tunnel " + version.getProperty("version", "development"));
      return;
    }
    String command = args[0];
    if (args.length == 2 && isHelp(args[1])) { commandHelp(command); return; }
    if ("server".equals(command) || "client".equals(command)) {
      String config;
      if (args.length == 1) config = command + ".properties";
      else if (args.length == 3 && ("-c".equals(args[1]) || "--config".equals(args[1]))) config = args[2];
      else throw new IllegalArgumentException("Usage: tunnel " + command + " [-c <config>]");
      if (!Files.isRegularFile(Path.of(config)))
        throw new IllegalArgumentException("Configuration not found: " + config);
      if ("server".equals(command)) Server.main(new String[] {config});
      else Client.main(new String[] {config});
      return;
    }
    Map<String, String> options = options(args);
    if ("init-server".equals(command)) initServer(options);
    else if ("init-client".equals(command)) initClient(options);
    else throw new IllegalArgumentException("Unknown command: " + command + ". Use tunnel --help.");
  }

  private static Map<String, String> options(String[] args) {
    Map<String, String> values = new HashMap<>();
    for (int i = 1; i < args.length; i += 2) {
      if (!args[i].startsWith("--") || i + 1 == args.length)
        throw new IllegalArgumentException("Options require a name and value: " + args[i]);
      if (values.put(args[i], args[i + 1]) != null)
        throw new IllegalArgumentException("Duplicate option: " + args[i]);
    }
    return values;
  }

  private static void checkOptions(Map<String, String> options, String... allowed) {
    java.util.Set<String> known = new java.util.HashSet<>(java.util.Arrays.asList(allowed));
    for (String key : options.keySet())
      if (!known.contains(key)) throw new IllegalArgumentException("Unknown option: " + key);
  }

  private static String host(Map<String, String> options) {
    String value = options.get("--server");
    if (value == null || !value.matches("[A-Za-z0-9][A-Za-z0-9.:-]{0,252}"))
      throw new IllegalArgumentException("--server requires a DNS hostname or IP address, without a port or URL");
    return value;
  }

  private static int port(Map<String, String> options, String key, int fallback) {
    int value = Integer.parseInt(options.getOrDefault(key, Integer.toString(fallback)));
    if (value < 1 || value > 65535) throw new IllegalArgumentException("Invalid port: " + key);
    return value;
  }

  private static Path directory(Map<String, String> options) throws IOException {
    Path dir = Path.of(options.getOrDefault("--dir", "state")).toAbsolutePath().normalize();
    Files.createDirectories(dir);
    return dir;
  }

  private static void absent(Path... paths) {
    for (Path path : paths)
      if (Files.exists(path)) throw new IllegalArgumentException("Refusing to overwrite: " + path);
  }

  private static void privateFile(Path file) throws IOException {
    try { Files.setPosixFilePermissions(file, PosixFilePermissions.fromString("rw-------")); }
    catch (UnsupportedOperationException ignored) { /* Windows inherits directory ACLs. */ }
  }

  private static void properties(Path path, Properties values) throws IOException {
    try (OutputStream out = Files.newOutputStream(path, java.nio.file.StandardOpenOption.CREATE_NEW)) {
      values.store(out, "Generated by tunnel; file paths are absolute");
    }
    privateFile(path);
  }

  private static void initServer(Map<String, String> options) throws Exception {
    checkOptions(options, "--server", "--dir", "--public-port");
    String hostname = host(options);
    int publicPort = port(options, "--public-port", 9090);
    if (publicPort == 7000 || publicPort == 7001 || publicPort == 8088)
      throw new IllegalArgumentException("Public port conflicts with control, work or management port");
    Path dir = directory(options), config = dir.resolve("server.properties");
    Path token = dir.resolve("token"), cert = dir.resolve("server.crt"), key = dir.resolve("server.key");
    absent(config, token, cert, key);
    String san = (hostname.contains(":") || hostname.matches("[0-9.]+") ? "IP:" : "DNS:") + hostname;
    // Generate in a private staging directory; a failed OpenSSL run leaves no partial installation.
    Path staging = Files.createTempDirectory(dir, ".init-");
    try {
      try { Files.setPosixFilePermissions(staging, PosixFilePermissions.fromString("rwx------")); }
      catch (UnsupportedOperationException ignored) { }
      Process openssl;
      Path opensslConfig = staging.resolve("openssl.cnf");
      Files.writeString(opensslConfig,
          "[req]\ndistinguished_name=dn\nx509_extensions=server\n[dn]\n[server]\n"
              + "basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\n"
              + "extendedKeyUsage=serverAuth\n", StandardCharsets.US_ASCII);
      try {
        openssl = new ProcessBuilder("openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes",
            "-config", opensslConfig.toString(),
            "-keyout", staging.resolve("server.key").toString(), "-out", staging.resolve("server.crt").toString(),
            "-days", "365", "-subj", "/CN=" + hostname, "-addext", "subjectAltName=" + san)
            .redirectError(ProcessBuilder.Redirect.INHERIT).redirectOutput(ProcessBuilder.Redirect.INHERIT).start();
      } catch (IOException e) {
        throw new IOException("init-server needs OpenSSL 1.1.1+. Install it or supply your own certificate using the example config.", e);
      }
      if (!openssl.waitFor(30, TimeUnit.SECONDS)) {
        openssl.destroyForcibly().waitFor();
        throw new IOException("Certificate generation timed out");
      }
      if (openssl.exitValue() != 0) throw new IOException("OpenSSL certificate generation failed");
      privateFile(staging.resolve("server.key"));
      byte[] random = new byte[32]; new SecureRandom().nextBytes(random);
      StringBuilder secret = new StringBuilder();
      for (byte b : random) secret.append(String.format("%02x", b & 255));
      Files.writeString(staging.resolve("token"), secret + "\n", StandardCharsets.US_ASCII);
      privateFile(staging.resolve("token"));
      Properties p = new Properties();
      p.setProperty("bindHost", "0.0.0.0"); p.setProperty("controlPort", "7000"); p.setProperty("workPort", "7001");
      p.setProperty("publicBindHost", "0.0.0.0"); p.setProperty("allowedPortStart", Integer.toString(publicPort));
      p.setProperty("allowedPortEnd", Integer.toString(publicPort)); p.setProperty("httpPort", "0");
      p.setProperty("managementPort", "8088"); p.setProperty("managementBindHost", "127.0.0.1");
      p.setProperty("tokenFile", token.toString()); p.setProperty("certFile", cert.toString()); p.setProperty("keyFile", key.toString());
      p.setProperty("storeFile", dir.resolve("mappings.properties").toString());
      properties(staging.resolve("server.properties"), p);
      Files.move(staging.resolve("server.key"), key); Files.move(staging.resolve("server.crt"), cert);
      Files.move(staging.resolve("token"), token); Files.move(staging.resolve("server.properties"), config);
      System.out.println("Created " + config);
      System.out.println("Start: tunnel server -c \"" + config + "\"");
      System.out.println("Allow inbound TCP 7000, 7001 and " + publicPort + " in the firewall/security group.");
      System.out.println("Securely copy only server.crt and token to the client. Keep server.key on this machine.");
    } finally {
      try (java.util.stream.Stream<Path> files = Files.list(staging)) {
        for (Path path : (Iterable<Path>) files::iterator) Files.deleteIfExists(path);
      }
      Files.deleteIfExists(staging);
    }
  }

  private static void initClient(Map<String, String> options) throws IOException {
    checkOptions(options, "--server", "--dir", "--token-file", "--ca-file", "--public-port", "--local-port", "--local-host", "--client-id");
    String hostname = host(options);
    int publicPort = port(options, "--public-port", 9090), localPort = port(options, "--local-port", 8080);
    Path token = Path.of(options.getOrDefault("--token-file", "token")).toAbsolutePath().normalize();
    Path ca = Path.of(options.getOrDefault("--ca-file", "server.crt")).toAbsolutePath().normalize();
    if (!Files.isRegularFile(token) || !Files.isRegularFile(ca))
      throw new IllegalArgumentException("Copy token and server.crt from the server first, or specify --token-file and --ca-file");
    String localHost = options.getOrDefault("--local-host", "127.0.0.1");
    if (localHost.contains(",") || localHost.contains("\n") || localHost.contains("\r"))
      throw new IllegalArgumentException("Invalid --local-host");
    Path file = directory(options).resolve("client.properties"); absent(file);
    Properties p = new Properties();
    p.setProperty("serverHost", hostname); p.setProperty("controlPort", "7000"); p.setProperty("workPort", "7001");
    p.setProperty("clientId", options.getOrDefault("--client-id", "home-pc"));
    p.setProperty("tokenFile", token.toString()); p.setProperty("caFile", ca.toString());
    p.setProperty("map.app", publicPort + "," + localHost + "," + localPort);
    properties(file, p);
    System.out.println("Created " + file);
    System.out.println("Start: tunnel client -c \"" + file + "\"");
  }

  private static boolean isHelp(String value) {
    return "--help".equals(value) || "-h".equals(value) || "/help".equals(value)
        || "help".equals(value);
  }

  private static void commandHelp(String command) {
    switch (command) {
      case "server":
      case "client":
        System.out.println("Usage: tunnel " + command + " [-c <config>]\n"
            + "  -c, --config FILE   Configuration file (default: " + command + ".properties)\n"
            + "  --help, -h, /help   Show help without starting the service\n"
            + "Example: tunnel " + command + " -c state/" + command + ".properties\n"
            + "Initialize first: tunnel init-" + command + " --help");
        break;
      case "init-server":
        System.out.println("Usage: tunnel init-server --server HOST [options]\n"
            + "  --server HOST       Required public IP or DNS hostname, without a port or URL\n"
            + "  --dir DIRECTORY     Output directory (default: state); existing files are not overwritten\n"
            + "  --public-port PORT  Allowed public mapping port (default: 9090)\n"
            + "Requires OpenSSL 1.1.1+. Generates server.properties, token, server.crt and server.key.\n"
            + "Allow inbound TCP 7000, 7001 and the public mapping port.\n"
            + "Example: tunnel init-server --server 203.0.113.10 --public-port 9090");
        break;
      case "init-client":
        System.out.println("Usage: tunnel init-client --server HOST [options]\n"
            + "  --server HOST       Required server IP or DNS hostname\n"
            + "  --dir DIRECTORY     Output directory (default: state); existing config is not overwritten\n"
            + "  --public-port PORT  Public mapping port (default: 9090)\n"
            + "  --local-port PORT   Private service port (default: 8080)\n"
            + "  --local-host HOST   Private service address (default: 127.0.0.1)\n"
            + "  --client-id ID      Client identity (default: home-pc)\n"
            + "  --token-file FILE   Shared token copied from server (default: token)\n"
            + "  --ca-file FILE      Trusted certificate copied from server (default: server.crt)\n"
            + "Example: tunnel init-client --server 203.0.113.10 --local-port 8080\n"
            + "Keep the server's private key on the server; do not copy server.key.");
        break;
      default:
        throw new IllegalArgumentException("Unknown command: " + command + ". Use tunnel --help.");
    }
  }

  private static void help() {
    System.out.println("Usage: tunnel <command> [options]\n"
        + "  server [-c server.properties]       Run the public relay\n"
        + "  client [-c client.properties]       Run the private-network agent\n"
        + "  init-server --server HOST [--dir state] [--public-port 9090]\n"
        + "      Generate a self-signed certificate and random token (needs OpenSSL 1.1.1+)\n"
        + "  init-client --server HOST [--dir state] [--public-port 9090] [--local-port 8080]\n"
        + "      [--token-file token] [--ca-file server.crt] [--local-host 127.0.0.1] [--client-id home-pc]\n"
        + "  --version                          Show version\n"
        + "  --help | -h | /help | help          Show help\n"
        + "  help <command>                     Show command options and examples\n"
        + "Config file paths supplied by hand are resolved from the working directory.");
  }
}
